//! 数据互通层：`share`。
//!
//! 单独一层的原因：NFO 既是「本地数据源」（读）又是「持久化介质」（写），
//! 塞进 `provider` 会让它承担写本地文件的职责，塞进 `core` 会破坏纯函数性。
//! 作为与 `provider` 平级的模块最干净（符合 B3「新增同级模块」）。
//!
//! ## 对视频文件零写入（本模块的硬红线）
//! - 只创建 `*.nfo` 文件，**从不打开视频文件做写入**；
//! - 默认**不覆盖**已存在的 NFO（`overwrite=false`），避免冲掉用户或别的软件写的；
//! - 目标路径若已存在同名文件，一律跳过并计入 `skipped`。
//! 也就是说：导出 NFO 是**加文件**，不是改文件。

